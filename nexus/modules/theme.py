from telethon.tl.custom import Message
from nexus.loader import BaseModule, module, command

EXTRA_THEMES = {
    "dracula_dark": {
        "border": "♰",
        "header_dec": "🦇 ɴ ᴇ x ᴜ s • ᴅ ʀ ᴀ ᴄ ᴜ ʟ ᴀ 🦇",
        "line": "╍" * 26,
        "bullet": "▪",
    },
    "emerald_matrix": {
        "border": "⌬",
        "header_dec": "⚡ ɴ ᴇ x ᴜ s • ᴍ ᴀ ᴛ ʀ ɪ x ⚡",
        "line": "═" * 26,
        "bullet": "❯",
    },
    "minimal_clean": {
        "border": "•",
        "header_dec": "[ NEXUS PROTOCOL ]",
        "line": "─" * 26,
        "bullet": "·",
    }
}

@module(
    name="Theme",
    description="Luxury theme manager, custom emoji palette configurer, and visual showcase.",
    author="txltedxgod",
    version="1.2.0"
)
class ThemeModule(BaseModule):
    async def on_load(self):
        # Register extra luxury themes
        for name, data in EXTRA_THEMES.items():
            self.ui.THEMES[name] = data
        
        # Load saved custom emojis
        custom_icons = self.get_config("custom_icons", {})
        for slot, emoji in custom_icons.items():
            self.ui.ICONS[slot] = emoji

    @command(
        name="settheme",
        description="Switch luxury visual theme preset.",
        usage=".settheme <name>"
    )
    async def cmd_settheme(self, message: Message, args: list):
        if not args:
            avail = ", ".join([f"`{t}`" for t in sorted(self.ui.THEMES.keys())])
            await message.edit(self.ui.info(f"Active Theme: **{self.ui.theme_name}**\nAvailable: {avail}"))
            return

        target = args[0].lower()
        if self.ui.set_theme(target):
            self.set_config("active_theme", target)
            await message.edit(self.ui.success(f"Visual theme switched to: **{target}**"))
        else:
            avail = ", ".join([f"`{t}`" for t in sorted(self.ui.THEMES.keys())])
            await message.edit(self.ui.error(f"Unknown theme. Choose from: {avail}"))

    @command(
        name="setemoji",
        description="Assign a custom emoji or character to a UI icon slot.",
        usage=".setemoji <slot> <emoji>"
    )
    async def cmd_setemoji(self, message: Message, args: list):
        if len(args) < 2:
            slots = ", ".join([f"`{s}`" for s in sorted(self.ui.ICONS.keys())])
            await message.edit(self.ui.warning(f"Usage: `.setemoji <slot> <emoji>`\nAvailable slots: {slots}"))
            return

        slot = args[0].lower()
        new_emoji = args[1]

        if slot not in self.ui.ICONS:
            await message.edit(self.ui.error(f"Slot `{slot}` does not exist."))
            return

        self.ui.ICONS[slot] = new_emoji
        icons = self.get_config("custom_icons", {})
        icons[slot] = new_emoji
        self.set_config("custom_icons", icons)

        await message.edit(self.ui.success(f"Slot `{slot}` updated to: {new_emoji}"))

    @command(
        name="emojipack",
        description="Display active custom emoji palette and icon mappings.",
        usage=".emojipack"
    )
    async def cmd_emojipack(self, message: Message, args: list):
        items = [f"`{slot:<10}` ➔ {icon}" for slot, icon in sorted(self.ui.ICONS.items())]
        card = self.ui.list_items("ACTIVE EMOJI PALETTE", items, icon="sparkles")
        await message.edit(card)

    @command(
        name="carddemo",
        description="Render a luxury UI card showcase demonstrating current aesthetics.",
        usage=".carddemo"
    )
    async def cmd_carddemo(self, message: Message, args: list):
        fields = {
            "Userbot Core": "Nexus v1.2.0 (Active)",
            "Visual Preset": self.ui.theme_name,
            "Custom Emojis": f"{len(self.ui.ICONS)} slots loaded",
            "Latency Probe": "31.40 ms (Ultra Fast)",
            "Security Level": "Level 5 (Encrypted)"
        }
        card = self.ui.card(
            title="LUXURY SHOWCASE",
            fields=fields,
            footer="Generated by Nexus Luxury UI Engine",
            icon="crown"
        )
        await message.edit(card)
